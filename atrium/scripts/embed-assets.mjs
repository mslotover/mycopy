#!/usr/bin/env node
/**
 * Packs the built front end (dist/) into the Worker itself.
 *
 * Normally Cloudflare stores the front end as static assets beside the Worker. Where that
 * upload isn't possible (for example behind a proxy that rewrites the upload's sign-in
 * header), `npm run deploy:embedded` ships the same files inside the Worker instead.
 *
 *   node scripts/embed-assets.mjs        pack dist/ and write wrangler.embedded.gen.jsonc
 *   node scripts/embed-assets.mjs --off  write an empty table (the normal build)
 */
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const out = "src/worker/static.gen.ts";
const head = "// Generated by scripts/embed-assets.mjs. Do not edit.\n";
if (process.argv.includes("--off")) {
  writeFileSync(out, `${head}export const STATIC: Record<string, { type: string; data: ArrayBuffer }> = {};\n`);
  process.exit(0);
}

const TYPES = { html: "text/html; charset=utf-8", js: "text/javascript; charset=utf-8", css: "text/css; charset=utf-8", svg: "image/svg+xml", json: "application/json", webmanifest: "application/manifest+json", png: "image/png", ico: "image/x-icon", woff2: "font/woff2", txt: "text/plain; charset=utf-8", map: "application/json" };
const walk = (dir) => readdirSync(dir).flatMap((name) => { const p = join(dir, name); return statSync(p).isDirectory() ? walk(p) : [p]; });
rmSync(".embed", { recursive: true, force: true });
mkdirSync(".embed");
const files = walk("dist").filter((f) => !f.endsWith(".map"));
const imports = [], entries = [];
files.forEach((file, i) => {
  cpSync(file, `.embed/${i}.bin`);
  const path = `/${relative("dist", file).split("\\").join("/")}`;
  imports.push(`import f${i} from "../../.embed/${i}.bin";`);
  entries.push(`  ${JSON.stringify(path)}: { type: ${JSON.stringify(TYPES[file.split(".").pop()] ?? "application/octet-stream")}, data: f${i} },`);
});
writeFileSync(out, `${head}${imports.join("\n")}\n\nexport const STATIC: Record<string, { type: string; data: ArrayBuffer }> = {\n${entries.join("\n")}\n};\n`);

// The same deployment settings, minus the static-asset store.
const config = JSON.parse(readFileSync("wrangler.jsonc", "utf8").replace(/^\s*\/\/.*$/gm, ""));
delete config.assets;
delete config.$schema;
writeFileSync("wrangler.embedded.gen.jsonc", `// Generated by scripts/embed-assets.mjs from wrangler.jsonc. Do not edit.\n${JSON.stringify(config, null, 2)}\n`);
console.log(`embedded ${files.length} files (${Math.round(files.reduce((n, f) => n + statSync(f).size, 0) / 1024)} KB)`);
